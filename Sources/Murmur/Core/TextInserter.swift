import AppKit
import ApplicationServices

enum TextInserter {
    enum Outcome { case pasted, copiedOnly }

    static var hasAccessibility: Bool { AXIsProcessTrusted() }

    static func requestAccessibility() {
        let key = kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String
        _ = AXIsProcessTrustedWithOptions([key: true] as CFDictionary)
    }

    /// Paste `text` into the focused field of the frontmost app, preserving
    /// the user's clipboard. Falls back to copying when Accessibility is off.
    @MainActor
    static func insert(_ text: String, restoreClipboard: Bool) async -> Outcome {
        let pb = NSPasteboard.general
        let saved: [[NSPasteboard.PasteboardType: Data]] = restoreClipboard
            ? (pb.pasteboardItems ?? []).map { item in
                Dictionary(uniqueKeysWithValues: item.types.compactMap { t in item.data(forType: t).map { (t, $0) } })
            }
            : []

        pb.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        // Ask clipboard managers not to record this transient write.
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        pb.writeObjects([item])
        let ourChange = pb.changeCount

        guard hasAccessibility else { return .copiedOnly }

        postCommandV()

        if restoreClipboard {
            // Give the target app time to read the pasteboard before we restore it.
            try? await Task.sleep(for: .milliseconds(450))
            if pb.changeCount == ourChange {
                pb.clearContents()
                if !saved.isEmpty {
                    let items = saved.map { dict -> NSPasteboardItem in
                        let i = NSPasteboardItem()
                        for (t, d) in dict { i.setData(d, forType: t) }
                        return i
                    }
                    pb.writeObjects(items)
                }
            }
        }
        return .pasted
    }

    private static func postCommandV() {
        let src = CGEventSource(stateID: .combinedSessionState)
        // Don't let a still-held trigger modifier (e.g. right ⌥) leak into the paste.
        src?.setLocalEventsFilterDuringSuppressionState([.permitLocalMouseEvents, .permitSystemDefinedEvents], state: .eventSuppressionStateSuppressionInterval)
        let v: CGKeyCode = 9
        let down = CGEvent(keyboardEventSource: src, virtualKey: v, keyDown: true)
        let up = CGEvent(keyboardEventSource: src, virtualKey: v, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cgAnnotatedSessionEventTap)
        up?.post(tap: .cgAnnotatedSessionEventTap)
    }
}
